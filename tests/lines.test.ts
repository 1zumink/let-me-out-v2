import { describe, expect, it } from 'vitest';
import { beats } from '../src/lines';

const texts = (b: ReturnType<typeof beats>) => b.map((x) => (x.pause ? '·' : x.text));

describe('реплики', () => {
  it('« … » внутри строки — пауза между облачками', () => {
    expect(texts(beats(['Посади меня тут ненадолго. … А сколько ты вообще можешь со мной пробыть? … Не отвечай. Я так спросил.']))).toEqual([
      'Посади меня тут ненадолго.',
      '·',
      'А сколько ты вообще можешь со мной пробыть?',
      '·',
      'Не отвечай. Я так спросил.',
    ]);
  });

  it('многоточие без пробела — часть реплики', () => {
    expect(texts(beats([{ who: 'hero', text: 'Ну… у всех телефоны.' }, '…Ну вот. Теперь они знают.']))).toEqual([
      'Ну… у всех телефоны.',
      '…Ну вот. Теперь они знают.',
    ]);
  });

  it('«…» отдельной строкой и по краям — тишина', () => {
    expect(texts(beats(['…', '… Подожди. Не надо. …']))).toEqual(['·', '·', 'Подожди. Не надо.']);
  });

  it('говорящий по умолчанию — герой', () => {
    expect(beats(['Эй.'])[0].who).toBe('hero');
    expect(beats([{ who: 'kostya', text: 'Да. Я знаю.' }])[0].who).toBe('kostya');
  });
});
